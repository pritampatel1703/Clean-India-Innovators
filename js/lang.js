function changeLanguage(lang) {
    localStorage.setItem('clean_india_lang', lang);
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Preserve icon if present at start
            const icon = el.querySelector('i');
            if (icon) {
                el.innerHTML = ''; // Clear text
                el.appendChild(icon); // Put icon back
                el.appendChild(document.createTextNode(' ' + translations[lang][key])); // Add text
            } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Update Dropdown Value
    const selector = document.getElementById('lang-selector');
    if (selector) selector.value = lang;
}

// Load saved language
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('clean_india_lang') || 'en';
    changeLanguage(savedLang);

    const selector = document.getElementById('lang-selector');
    if (selector) {
        selector.addEventListener('change', (e) => {
            changeLanguage(e.target.value);
        });
    }
});
